#!/usr/bin/env bash
#
# Tests the harness (base-script.sh) against the contract the judge relies on.
#
# The images are built by concatenating a language script onto base-script.sh, so
# this test does the same thing with a language script of its own and runs the
# result against a workspace laid out exactly like the one the judge prepares.
# That makes the contract checkable without Docker:
#
#   1. Milestones carry the run's nonce, so a submission cannot fake progress.
#   2. container.config is gone before any submitted code runs (a Makefile
#      submission can execute code during compilation).
#   3. The per-case limits the judge sends reach the monitor.
#   4. Whatever the graded program leaves running is killed before the results
#      are collected, so it cannot touch them.
#   5. The limits are exactly the ones container.config carries: a zero byte limit
#      means "no limit", and a missing CPU or compilation budget fails the run
#      instead of falling back to an image default.
#
# Usage: runners/test/harness.test.sh

set -u

script_dir="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
runners_dir="${script_dir}/.."
base_script="${runners_dir}/base/base-script.sh"

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

failures=0
checks=0

fail() {
    echo "FAIL: $*" >&2
    failures=$((failures + 1))
}

check() {
    local description="$1"
    shift
    checks=$((checks + 1))
    if ! "$@"; then
        fail "${description}"
    fi
}

check_eq() {
    local description="$1" expected="$2" actual="$3"
    checks=$((checks + 1))
    if [ "${actual}" != "${expected}" ]; then
        fail "${description} (got '${actual}', want '${expected}')"
    fi
}

echo "==> building the monitor and a limit probe"
if ! gcc -Wall -O2 \
    "${runners_dir}/../monitor/src/main.c" \
    "${runners_dir}/../monitor/src/monitor.c" \
    -o "${work}/monitor"; then
    echo "could not build the monitor" >&2
    exit 1
fi

# Reports the limits as the kernel sees them, in bytes, so the assertions do not
# depend on how `ulimit` chooses to print each one.
cat >"${work}/limits.c" <<'EOF'
#include <stdio.h>
#include <sys/resource.h>

static void report(const char *name, int resource) {
    struct rlimit limit;
    if (getrlimit(resource, &limit) != 0) {
        printf("%s=error\n", name);
        return;
    }
    if (limit.rlim_cur == RLIM_INFINITY)
        printf("%s=unlimited\n", name);
    else
        printf("%s=%llu\n", name, (unsigned long long) limit.rlim_cur);
}

int main(void) {
    report("fs_bytes", RLIMIT_FSIZE);
    report("as_bytes", RLIMIT_AS);
    report("stack_bytes", RLIMIT_STACK);
    return 0;
}
EOF
gcc -O2 "${work}/limits.c" -o "${work}/limits" || exit 1

# The graded program runs with the environment the harness inherited, which is
# how the probe above is found.
export LIMITS_PROBE="${work}/limits"
inherited_stack="$("${work}/limits" | sed -n 's/^stack_bytes=//p')"

# build_image <out> [extra language lines] — base script + language script, the
# way the Dockerfiles build /usr/bin/runcodes by appending the language script to
# the base one. The extra lines are inserted where a language script sets its own
# defaults, so a test can give the image a default the judge has to override.
build_image() {
    local out="$1" extra="${2:-}"
    {
        cat "${base_script}"
        cat <<'LANG'

# --- language script (a Python-like image: no compilation, a script to run) ---
if ! compgen -G "src/?akefile" >/dev/null; then
    compilation_command='./compile-check.sh'
    run_command="bash ${src_file}"
fi
LANG
        if [ -n "${extra}" ]; then
            printf '%s\n' "${extra}"
        fi
        cat <<'LANG'

compile "${compilation_command}"

if [ -s "${compilation_error}" ]; then
    exit 1
fi

run_tests "${run_command}"
LANG
    } >"${out}"
    chmod +x "${out}"
}

# prep_workspace <dir> <nonce> — a workspace shaped like prepareWorkspace() in the
# judge. `monitor_bin` is only set here so the test can use the locally built
# binary; the images bake in /usr/bin/monitor and the judge never sends that key.
prep_workspace() {
    local ws="$1" nonce="$2"
    mkdir -p "${ws}/src" "${ws}/test_1" "${ws}/test_2"

    cat >"${ws}/src/prog.sh" <<'PROG'
#!/bin/bash
mode="$(cat)"
case "${mode}" in
    report)
        echo "generated by the case" >produced.txt
        # Larger than the collection cap the harness used to impose. Only written
        # when the case has no file-size limit: elsewhere the kernel would stop
        # the write (RLIMIT_FSIZE), which is the point of that limit.
        if [ "$(ulimit -f)" = "unlimited" ]; then
            head -c 9437184 /dev/zero >large.bin
        fi
        "${LIMITS_PROBE}"
        if [ -e ../container.config ]; then
            echo "config=present"
        else
            echo "config=absent"
        fi
        ;;
    daemonize)
        # Something that outlives this case and tries to tamper with the results
        # of the case that already ran.
        ( sleep 1; printf 'TAMPERED\n' >>../1.output; : >../tampered.marker ) &
        echo "ok"
        ;;
esac
PROG

    # Runs during the compile phase, before a real language's compiler. Records
    # the limits the compile process was given, which is the only way to see the
    # effective `monitor_max_*` from inside the image.
    cat >"${ws}/src/compile-check.sh" <<'CHECK'
#!/bin/bash
if [ -e ../container.config ]; then
    echo "config was still readable during compilation" >&2
    exit 1
fi
if [ -e ../compile-warning ]; then
    echo "warning: this compiler warning must not fail the run" >&2
fi
if [ -e ../compile-failure ]; then
    echo "error: the compiler failed" >&2
    exit 1
fi
if [ -e ../compile-failure-silent ]; then
    exit 1
fi
"${LIMITS_PROBE}" >../compile-limits.txt
CHECK
    chmod +x "${ws}/src/compile-check.sh"

    printf 'report\n' >"${ws}/1.in"
    printf 'daemonize\n' >"${ws}/2.in"

    cat >"${ws}/container.config" <<EOF
monitor_bin=${work}/monitor
monitor_max_fs=5242880
monitor_max_ms=268435456
compilation_timeout=10
src_file='prog.sh'
run_nonce='${nonce}'
t_1=5
ms_1=67108864
fs_1=1048576
stack_1=1048576
t_2=5
ms_2=0
fs_2=0
stack_2=0
EOF
}

echo "==> full run"
image="${work}/runcodes"
build_image "${image}"
ws="${work}/ws"
prep_workspace "${ws}" "0123456789abcdef"

if ! (cd "${ws}" && "${image}") >"${work}/log" 2>"${work}/log.err"; then
    echo "the harness exited non-zero; log:" >&2
    cat "${work}/log" >&2
    cat "${work}/log.err" >&2
    exit 1
fi

# 1. Milestones carry the nonce.
check "compilation.start carries the nonce" \
    grep -q '^compilation.start 0123456789abcdef$' "${work}/log"
check "compilation.done carries the nonce" \
    grep -q '^compilation.done 0123456789abcdef$' "${work}/log"
check "run.start carries the nonce" \
    grep -q '^run.start 0123456789abcdef$' "${work}/log"
check "run.done carries the nonce" \
    grep -q '^run.done 0123456789abcdef$' "${work}/log"
check "no bare milestone is printed by the harness" \
    bash -c '! grep -qE "^(compilation\.(start|done)|run\.(start|done))$" "$1"' _ "${work}/log"
# Each case announces its completion, after its artifacts are in place, so the
# judge can publish the result before the suite ends.
check "every case announces completion with the nonce" \
    bash -c 'test "$(grep -cE "^case\.done [0-9]+ 0123456789abcdef$" "$1")" = "2"' _ "${work}/log"

# 2. The config is gone before submitted code runs.
check "container.config was removed before the compile phase" \
    test ! -e "${ws}/container.config"
check_eq "the graded program cannot read the config either" "config=absent" \
    "$(grep '^config=' "${ws}/1.output")"

# 3. Per-case limits reached the monitor, in bytes.
check_eq "the per-case file size limit is applied" "fs_bytes=1048576" \
    "$(grep '^fs_bytes=' "${ws}/1.output")"
check_eq "the per-case memory limit is applied" "as_bytes=67108864" \
    "$(grep '^as_bytes=' "${ws}/1.output")"
check_eq "the per-case stack limit is applied" "stack_bytes=1048576" \
    "$(grep '^stack_bytes=' "${ws}/1.output")"

echo "==> compiler warnings do not fail valid submissions"
ws_warn="${work}/ws-warning"
prep_workspace "${ws_warn}" "nonce-warning"
: >"${ws_warn}/compile-warning"
if ! (cd "${ws_warn}" && "${image}") >"${work}/log-warning" 2>&1; then
    echo "the harness failed a compilation that only warned" >&2
    cat "${work}/log-warning" >&2
    exit 1
fi
check "a warning-only compilation continued to the run" \
    grep -q '^run.done nonce-warning$' "${work}/log-warning"
check "the warning was not left in compilation.err" \
    test ! -s "${ws_warn}/compilation.err"
check "the warning was preserved as a diagnostic" \
    grep -q 'this compiler warning must not fail the run' "${ws_warn}/compilation.warnings"
check "the warning was copied to the output files" \
    test -e "${ws_warn}/outputfiles/compilation.warnings"

echo "==> a failed compilation with empty stderr still stops the run"
ws_fail="${work}/ws-compile-failure"
prep_workspace "${ws_fail}" "nonce-compile-failure"
: >"${ws_fail}/compile-failure-silent"
if (cd "${ws_fail}" && "${image}") >"${work}/log-compile-failure" 2>&1; then
    echo "the harness accepted a compiler that exited non-zero" >&2
    cat "${work}/log-compile-failure" >&2
    exit 1
fi
check "the silent compiler failure produced an error" \
    test -s "${ws_fail}/compilation.err"
check "the run never started after the failed compilation" \
    bash -c '! grep -q "^run.start" "$1"' _ "${work}/log-compile-failure"

# 4. Nothing the graded program left behind touched the results.
check_eq "the daemonising case reported normally" "ok" \
    "$(cat "${ws}/2.output")"
check "the earlier case's output was not tampered with" \
    bash -c '! grep -q TAMPERED "$1"' _ "${ws}/1.output"
check "the daemonised process never ran again" \
    test ! -e "${ws}/tampered.marker"

# The report is a regular file written by the monitor, not by the shell.
check "the monitor wrote the case report" \
    grep -q '^time=' "${ws}/1.monitor_out"
check "the case report is not a symlink" \
    test ! -L "${ws}/1.monitor_out"

# Files the program wrote are collected into the artifact, with their relative
# path, so the student can download them.
check "a file the program wrote is collected for download" \
    test -f "${ws}/outputfiles/case_1/produced.txt"
# The directory proves which harness the image carries, so a case that wrote
# nothing still gets one.
check "a case that wrote nothing still has a collection directory" \
    test -d "${ws}/outputfiles/case_2"

echo "==> a zero byte limit means no limit"
ws_zero="${work}/ws-zero"
prep_workspace "${ws_zero}" "nonce-zero"
rm -rf "${ws_zero}/test_2"
sed -i 's/^ms_1=.*/ms_1=0/; s/^fs_1=.*/fs_1=0/' "${ws_zero}/container.config"
if ! (cd "${ws_zero}" && "${image}") >"${work}/log-zero" 2>&1; then
    echo "the harness exited non-zero with explicit no-limit values" >&2
    cat "${work}/log-zero" >&2
    exit 1
fi
check_eq "a zero memory limit is passed through as no limit" "as_bytes=unlimited" \
    "$(grep '^as_bytes=' "${ws_zero}/1.output")"
check_eq "a zero file size limit is passed through as no limit" "fs_bytes=unlimited" \
    "$(grep '^fs_bytes=' "${ws_zero}/1.output")"
# The old harness dropped anything from 8 MiB up. The bound is the case's
# file-size limit, so with no limit the file is collected for download.
check "a file larger than 8 MiB is collected when the case has no size limit" \
    test -f "${ws_zero}/outputfiles/case_1/large.bin"
check_eq "the collected large file is intact" "9437184" \
    "$(wc -c <"${ws_zero}/outputfiles/case_1/large.bin")"

echo "==> the images carry no defaults to fall back to"
# A missing CPU budget cannot be guessed: the harness must refuse to run the
# case instead of picking a timeout of its own.
ws_no_timeout="${work}/ws-no-timeout"
prep_workspace "${ws_no_timeout}" "nonce-no-timeout"
rm -rf "${ws_no_timeout}/test_2"
sed -i '/^t_1=/d' "${ws_no_timeout}/container.config"
if (cd "${ws_no_timeout}" && "${image}") >"${work}/log-no-timeout" 2>&1; then
    echo "the harness accepted a case without a CPU budget" >&2
    cat "${work}/log-no-timeout" >&2
    exit 1
fi
check "the missing case timeout is named" \
    grep -q 'container.config is missing t_1' "${work}/log-no-timeout"

# The compilation timeout is the judge's, and the image has no say in it. The
# judge asks for 3 seconds and the compile command would run for 600, so a
# compile still running after 30 seconds means the wrong value won — which is
# also the failure this guards against, since without the outer bound the test
# would hang for ten minutes.
echo "==> the judge's compilation timeout is applied"
image_timeout="${work}/runcodes-timeout"
build_image "${image_timeout}" "compilation_command='sleep 600'"

ws_timeout="${work}/ws-timeout"
prep_workspace "${ws_timeout}" "nonce-timeout"
rm -rf "${ws_timeout}/test_2"
sed -i 's/^compilation_timeout=10$/compilation_timeout=3/' "${ws_timeout}/container.config"
if (cd "${ws_timeout}" && timeout 30 "${image_timeout}") >"${work}/log-timeout" 2>&1; then
    echo "the harness accepted a compilation that timed out" >&2
    cat "${work}/log-timeout" >&2
    exit 1
fi
check "the compile phase was cut off instead of running for 600 seconds" \
    bash -c 'test ! -e "$1/1.output"' _ "${ws_timeout}"
check "the run did not execute tests after the compile timeout" \
    bash -c '! grep -q "^run.start" "$1"' _ "${work}/log-timeout"
check "the compile timeout was reported as a compilation error" \
    grep -Eq 'SIGKILL|timeout|exit status' "${ws_timeout}/compilation.err"
check "the run reported the compile phase" \
    grep -q '^compilation.done nonce-timeout$' "${work}/log-timeout"

# And a compilation budget is required, like the case's.
ws_no_compile_timeout="${work}/ws-no-compile-timeout"
prep_workspace "${ws_no_compile_timeout}" "nonce-no-compile-timeout"
rm -rf "${ws_no_compile_timeout}/test_2"
sed -i '/^compilation_timeout=/d' "${ws_no_compile_timeout}/container.config"
if (cd "${ws_no_compile_timeout}" && "${image}") >"${work}/log-no-compile-timeout" 2>&1; then
    echo "the harness accepted a run without a compilation budget" >&2
    cat "${work}/log-no-compile-timeout" >&2
    exit 1
fi
check "the missing compilation timeout is named" \
    grep -q 'container.config is missing compilation_timeout' "${work}/log-no-compile-timeout"

echo "==> a submission cannot fake a milestone"
ws_forge="${work}/ws-forge"
prep_workspace "${ws_forge}" "nonce-forge"
cat >"${ws_forge}/src/prog.sh" <<'FORGE'
#!/bin/bash
cat >/dev/null
# A program under test printing the milestones it would like the judge to see.
echo "compilation.done"
echo "run.done"
echo "ok"
FORGE
if ! (cd "${ws_forge}" && "${image}") >"${work}/log-forge" 2>&1; then
    echo "the harness exited non-zero for the forging submission" >&2
    cat "${work}/log-forge" >&2
    exit 1
fi
check "no bare milestone reaches the container log" \
    bash -c 'test "$(grep -c "^run.done$" "$1")" = "0"' _ "${work}/log-forge"
check "the real milestone appears exactly once" \
    bash -c 'test "$(grep -c "^run.done nonce-forge$" "$1")" = "1"' _ "${work}/log-forge"
# The forged lines went to the program's own output, where they are graded.
check_eq "the forged milestones landed in the case output" "run.done" \
    "$(grep -m1 '^run.done$' "${ws_forge}/1.output")"

echo
if [ "${failures}" -eq 0 ]; then
    echo "all ${checks} checks passed"
    exit 0
fi

echo "${failures} of ${checks} checks failed" >&2
exit 1
