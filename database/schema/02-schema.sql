CREATE TABLE commit_phase_timings (
  commit_id int NOT NULL REFERENCES commits (id) ON DELETE CASCADE,
  phase commit_phase_t NOT NULL,
  duration_ms int NOT NULL CHECK (duration_ms >= 0),
  cpu_ms int CHECK (cpu_ms IS NULL OR cpu_ms >= 0),
  mem_peak_bytes bigint CHECK (mem_peak_bytes IS NULL OR mem_peak_bytes >= 0),
  started_at TIMESTAMP WITH TIME ZONE,
  finished_at TIMESTAMP WITH TIME ZONE,
  source text DEFAULT 'judge' NOT NULL CHECK (source IN ('judge', 'monitor', 'harness')),
  detail jsonb,
  PRIMARY KEY (commit_id, phase)
);

-- Operational alerts addressed to the platform administrators ("Alertas" in the
-- admin panel). The judge records one when a run cannot be completed for an
-- infrastructure reason — a container that never prints its first milestone is
-- the case this was introduced for — and the backend records its own for
-- conditions only it can detect. Every inserted row is also emailed to the
-- administrators; the (commit_id, code) unique index makes a replayed judge
-- event persist once, and therefore notify once.
--
-- This is unrelated to a class's bulletin board (`offering_posts`), which is
-- course material, not an operational failure.
CREATE TABLE system_alerts (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  severity text DEFAULT 'warning' NOT NULL CHECK (severity IN ('warning', 'critical')),
  -- Stable machine-readable identifier ("startup_timeout"), used to group
  -- repeated incidents and as the email deduplication key.
  code text NOT NULL,
  source text DEFAULT 'judge' NOT NULL CHECK (source IN ('judge', 'backend')),
  -- The run the alert is about, when it is about one. SET NULL keeps the alert
  -- after its commit row is gone.
  commit_id int REFERENCES commits (id) ON DELETE SET NULL,
  message text NOT NULL,
  -- Free-form structured context (language, image, wait seconds, …).
  details jsonb,
  acknowledged_at TIMESTAMP WITH TIME ZONE,
  acknowledged_by int REFERENCES users (id) ON DELETE SET NULL
);

-- One row per account: a resend replaces the row, and a successful verification
-- retires it. The token itself is never stored: token_hash is its SHA-256, so a
-- database dump cannot be turned into working links.
CREATE TABLE email_verification_tokens (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id int UNIQUE NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash text UNIQUE NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  consumed_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

-- Password recovery uses the same one-row-per-account, hash-only design as email
-- verification. A new request replaces the row, so exactly one link is live; a
-- successful reset marks it consumed.
CREATE TABLE password_reset_tokens (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id int UNIQUE NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash text UNIQUE NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  consumed_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

-- Indexes.
--
-- PostgreSQL indexes primary keys and UNIQUE constraints, and nothing else. A
-- foreign key gets no index automatically, so without these every lookup by
-- parent id is a sequential scan, and so is the check PostgreSQL runs for each
-- ON DELETE CASCADE.
CREATE INDEX idx_offerings_owner_id ON offerings (owner_id);
-- The enrollments PK is (user_id, offering_id), which a lookup by offering alone
-- cannot use.
CREATE INDEX idx_enrollments_offering_id ON enrollments (offering_id);
CREATE INDEX idx_exercises_offering_id ON exercises (offering_id);
CREATE INDEX idx_exercises_creator_id ON exercises (creator_id);
CREATE INDEX idx_exercises_attached_files_exercise_id ON exercises_attached_files (exercise_id);
CREATE INDEX idx_exercises_compilation_files_exercise_id ON exercises_compilation_files (exercise_id);
-- The join table's PK is (exercise_id, allowed_file_type_id), so only the second
-- column needs an index of its own.
CREATE INDEX idx_exercises_allowed_file_types_type_id ON exercises_allowed_file_types (allowed_file_type_id);
CREATE INDEX idx_exercises_test_cases_exercise_id ON exercises_test_cases (exercise_id);
CREATE INDEX idx_exercises_test_cases_files_case_id ON exercises_test_cases_files (exercise_test_case_id);
CREATE INDEX idx_commits_user_id ON commits (user_id);
CREATE INDEX idx_commits_exercise_id ON commits (exercise_id);
CREATE INDEX idx_commits_allowed_file_type_id ON commits (allowed_file_type_id);
-- The limit-alert aggregation and the statistics/reporting queries filter
-- commits by created_at over a rolling window; without a plain index on the
-- column each pass scans the whole table. The partial queued index below cannot
-- serve them.
CREATE INDEX idx_commits_created_at ON commits (created_at);
-- The results PK is (commit_id, exercise_test_case_id): commit_id is covered, the
-- case id is not.
CREATE INDEX idx_results_exercise_test_case_id ON commits_exercise_test_cases_results (exercise_test_case_id);
-- The statistics pivot filters by phase and joins by commit; the PK covers the
-- commit lookup, so only the phase needs its own index.
CREATE INDEX idx_commit_phase_timings_phase ON commit_phase_timings (phase);
-- The class page lists a post's comments together, oldest first, and the board
-- lists posts newest first.
CREATE INDEX idx_offering_posts_offering_id
  ON offering_posts (offering_id, created_at DESC);
CREATE INDEX idx_offering_post_comments_post_id
  ON offering_post_comments (post_id, created_at);
-- The foreign key's delete check, and the lookup of a reply's parent.
CREATE INDEX idx_offering_post_comments_parent
  ON offering_post_comments (parent_comment_id);
-- The panel lists alerts newest first, and the open count drives the badge; the
-- partial index serves the second without reading the acknowledged history.
CREATE INDEX idx_system_alerts_created_at ON system_alerts (created_at DESC);
CREATE INDEX idx_system_alerts_open ON system_alerts (created_at DESC)
  WHERE acknowledged_at IS NULL;
-- One alert per (commit, code): a replayed judge event must not duplicate it.
CREATE UNIQUE INDEX system_alerts_commit_code_key ON system_alerts (commit_id, code)
  WHERE commit_id IS NOT NULL;
-- The notifier looks a student up when an exercise enters a reminder window, and
-- the PK covers exercise_id; this index serves the reverse lookup.
CREATE INDEX idx_exercise_deadline_notifications_user_id
  ON exercise_deadline_notifications (user_id);

-- At most one in-flight email change per address. The partial predicate keeps
-- the many NULL pending_email rows out of the index.
CREATE UNIQUE INDEX users_pending_email_key ON users (pending_email)
  WHERE pending_email IS NOT NULL;

-- Email is case-insensitive in the application. These functional indexes make
-- the database enforce the same rule and let lower(email) lookups use an index;
-- the original case-sensitive UNIQUE constraints stay for compatibility.
CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));
CREATE UNIQUE INDEX users_pending_email_lower_key ON users (lower(pending_email))
  WHERE pending_email IS NOT NULL;

-- The judge's claim loop runs continuously against the fastest-growing table in
-- the schema:
--
--   SELECT ... FROM commits WHERE status = 'queued' ORDER BY created_at LIMIT 1
--
-- The partial index serves both the filter and the ORDER BY, and stays small as
-- the backlog drains. On an existing database, create it (and the indexes above)
-- with CREATE INDEX CONCURRENTLY to avoid holding a write lock on commits.
CREATE INDEX idx_commits_queued ON commits (created_at) WHERE status = 'queued';
-- Row-level security at the service-role boundary.
--
-- The backend connects as `runcodes_app` and still relies on the handlers for
-- per-user authorization; these policies do not filter individual rows. What
-- they add is a database-enforced boundary around the judge: the judge role is
-- denied every table in this list even if a future migration or manual grant is
-- too broad. The backend and the table owner (`runcodes`, used by migrations and
-- the seed) keep their existing full access.
--
-- Tables the judge needs (commits, exercises and the test-case tables) are not
-- enabled here, because the judge must read/update rows across all users.

ALTER TABLE "users" ENABLE ROW LEVEL SECURITY;
