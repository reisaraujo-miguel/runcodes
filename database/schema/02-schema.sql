CREATE TYPE commit_status_t AS ENUM ('pending', 'queued', 'compiling', 'compilation_error', 'running', 'completed', 'uncompleted', 'server_error', 'plagiarism', 'timeout');

CREATE TABLE commits (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id int NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  exercise_id int NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  status commit_status_t DEFAULT 'pending' NOT NULL,
  num_correct_cases int DEFAULT 0 NOT NULL,
  score numeric(5, 2) DEFAULT 0 NOT NULL CHECK (score >= 0 AND score <= 100),
  compiled boolean,
  compilation_message text,
  compilation_started TIMESTAMP WITH TIME ZONE,
  compilation_finished TIMESTAMP WITH TIME ZONE,
  compilation_error text,
  ip inet,
  s3_key text,
  -- The allowed-file-type row that matched the submitted filename. Storing the
  -- choice at submission time lets the language statistics group by language
  -- without re-parsing the object key, and keeps ZIP submissions distinguishable
  -- from the languages the judge may detect inside them.
  allowed_file_type_id int REFERENCES allowed_file_types (id) ON DELETE SET NULL
);

CREATE TABLE commit_test_case_limits (
  commit_id int NOT NULL REFERENCES commits (id) ON DELETE CASCADE,
  exercise_test_case_id int NOT NULL REFERENCES exercises_test_cases (id) ON DELETE CASCADE,
  -- The limits resolved for the language of this commit when it was queued, so
  -- grading never depends on a configuration edited after the submission.
  cpu_time_limit_seconds int NOT NULL,
  mem_usage_limit_bytes bigint NOT NULL,
  stack_limit_bytes bigint NOT NULL,
  file_size_limit_bytes bigint NOT NULL,
  PRIMARY KEY (commit_id, exercise_test_case_id)
);

CREATE TYPE commit_exercise_test_case_status_t AS ENUM ('killed_with_signal', 'correct', 'bad_formatted_output');

CREATE TYPE case_interruption_reason_t AS ENUM (
  'timeout',
  'cpu_limit',
  'memory_limit',
  'stack_limit',
  'file_size_limit',
  'signal',
  'monitor_error',
  'output_error',
  'server_error'
