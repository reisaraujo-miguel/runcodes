CREATE TYPE user_t AS ENUM ('student', 'professor', 'admin', 'dev');

CREATE TABLE users (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text UNIQUE NOT NULL,
  org_id text UNIQUE,
  password_hash text NOT NULL,
  role user_t DEFAULT 'student' NOT NULL,
  confirmed boolean DEFAULT FALSE NOT NULL,
  -- Incremented to invalidate every session issued for the account. A JWT
  -- carries the value it was issued with; the request guard compares it with
  -- this column.
  token_version integer DEFAULT 1 NOT NULL,
  -- An email change requested but not yet verified. The current email stays
  -- active until the link sent to this address is used.
  pending_email text,
  -- Whether the in-browser code editor is enabled for this user. New users
  -- start with it on; the preference is editable on the profile and submission
  -- pages.
  code_editor_enabled boolean DEFAULT TRUE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

CREATE TABLE offerings (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  owner_id int NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  end_date TIMESTAMP WITH TIME ZONE NOT NULL,
  visible_to_enroll boolean DEFAULT TRUE NOT NULL,
  enrollment_code text UNIQUE,
  description text,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  CONSTRAINT offerings_enrollment_code_length
    CHECK (enrollment_code IS NULL OR length(enrollment_code) >= 6)
);

CREATE TYPE enrollment_role_t AS ENUM ('student', 'professor', 'monitor');

CREATE TABLE enrollments (
  user_id int REFERENCES users (id) ON DELETE CASCADE,
  offering_id int REFERENCES offerings (id) ON DELETE CASCADE,
  role enrollment_role_t NOT NULL,
  banned boolean DEFAULT FALSE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  PRIMARY KEY (user_id, offering_id)
);

-- A class's bulletin board ("Mural"): announcements written by the professors
-- and monitors, and the discussion under each one. A new post emails the
-- enrolled students; a comment emails the class staff, or — when it answers a
-- student's comment — only that student.
CREATE TABLE offering_posts (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offering_id int NOT NULL REFERENCES offerings (id) ON DELETE CASCADE,
  author_id int NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  title text NOT NULL,
  body text NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  -- Reserved for a future edit action; a post is never rewritten today.
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

CREATE TABLE offering_post_comments (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id int NOT NULL REFERENCES offering_posts (id) ON DELETE CASCADE,
  -- The comment this one answers, NULL for a comment on the post itself.
  parent_comment_id int REFERENCES offering_post_comments (id) ON DELETE CASCADE,
  author_id int NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  body text NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

CREATE TABLE allowed_file_types (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text UNIQUE NOT NULL,
  extension text UNIQUE NOT NULL,
